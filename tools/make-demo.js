/* Generates sample/demo.pgn: synthetic self-play games for "You" vs "Opponent" (deterministic).
 * "You" is deliberately error-prone so the demo shows realistic weaknesses. Not real games. */
const fs = require('fs');
const C = require('../js/chess.js');
const { Engine } = require('../js/engine.js');
let seed = 12345;
const rand = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const OPENINGS = [
  ['Italian Game', 'C50', 'e4 e5 Nf3 Nc6 Bc4 Bc5 c3 Nf6'],
  ['Sicilian Defense: Najdorf Variation', 'B90', 'e4 c5 Nf3 d6 d4 cxd4 Nxd4 Nf6 Nc3 a6'],
  ['Queen’s Gambit Declined', 'D30', 'd4 d5 c4 e6 Nc3 Nf6 Bg5 Be7'],
  ['King’s Indian Defense', 'E60', 'd4 Nf6 c4 g6 Nc3 Bg7 e4 d6'],
  ['French Defense: Advance Variation', 'C02', 'e4 e6 d4 d5 e5 c5 c3 Nc6'],
  ['English Opening', 'A20', 'c4 e5 Nc3 Nf6 g3 d5 cxd5 Nxd5'],
  ['Scotch Game', 'C45', 'e4 e5 Nf3 Nc6 d4 exd4 Nxd4 Nf6'],
];
const out = [];
const GAMES = 28;
for (let g = 0; g < GAMES; g++) {
  const [oname, eco, line] = OPENINGS[g % OPENINGS.length];
  const youWhite = g % 2 === 0;
  const pos = new C.Position(); const eng = new Engine();
  const sans = [], clocks = [];
  const base = 180; const clk = [base, base];
  for (const s of line.split(' ')) { const m = pos.parseSAN(s); if (!m) break; sans.push(pos.san(m)); pos.makeMove(m); }
  let result = '1/2-1/2', term = 'Normal';
  for (let ply = sans.length; ply < 180; ply++) {
    const legal = pos.legalMoves();
    if (!legal.length) { result = pos.inCheck() ? (pos.turn === 0 ? '0-1' : '1-0') : '1/2-1/2'; break; }
    if (pos.isInsufficientMaterial() || pos.half >= 100 || pos.isRepetition()) { result = '1/2-1/2'; break; }
    const you = (pos.turn === 0) === youWhite;
    const r = eng.search(pos, { depth: you ? 2 : 3, nodes: 20000 });
    if (Math.abs(r.score) > 1100) { result = (r.score > 0) === (pos.turn === 0) ? '1-0' : '0-1'; term = 'Normal'; break; }
    let m = r.move;
    const blunderP = you ? (ply < 30 ? 0.05 : 0.14) : 0.05;
    if (rand() < blunderP) m = legal[Math.floor(rand() * legal.length)];
    const c = pos.turn;
    const spend = you ? Math.min(clk[c], 1 + rand() * (ply < 24 ? 5 : 6)) : Math.min(clk[c], 1 + rand() * 4);
    clk[c] = Math.max(1, clk[c] - spend);
    clocks.push(clk[c]);
    sans.push(pos.san(m)); pos.makeMove(m);
  }
  const d = new Date(Date.UTC(2026, 9, 1 + Math.floor(g * 0.9)));
  const date = d.toISOString().slice(0, 10).replace(/-/g, '.');
  const you = 'You', opp = 'Opponent' + (g % 5 + 1);
  let txt = `[Event "Demo blitz"]\n[Site "demo"]\n[Date "${date}"]\n[White "${youWhite ? you : opp}"]\n[Black "${youWhite ? opp : you}"]\n[Result "${result}"]\n`;
  txt += `[WhiteElo "${youWhite ? 1180 + g : 1230}"]\n[BlackElo "${youWhite ? 1230 : 1180 + g}"]\n[TimeControl "180"]\n[ECO "${eco}"]\n[Opening "${oname}"]\n[Termination "${term}"]\n\n`;
  let mt = '';
  sans.forEach((s, i) => {
    if (i % 2 === 0) mt += `${i / 2 + 1}. `;
    const ck = i >= line.split(' ').length ? clocks[i - line.split(' ').length] : null;
    const f = (x) => `${String(Math.floor(x / 60)).padStart(2, "0")}:${String(Math.floor(x % 60)).padStart(2, "0")}`;
    mt += s + (ck != null ? ` {[%clk 0:${f(ck)}]}` : '') + ' ';
  });
  out.push(txt + mt.trim() + ' ' + result + '\n');
}
const all = out.join('\n');
fs.writeFileSync(__dirname + '/../sample/demo.pgn', all);
fs.writeFileSync(__dirname + '/../js/demo-data.js', '/* Generated by tools/make-demo.js — synthetic self-play games for the demo button. */\nwindow.DEMO_PGN = ' + JSON.stringify(all) + ';\n');
console.log('wrote', out.length, 'games');
